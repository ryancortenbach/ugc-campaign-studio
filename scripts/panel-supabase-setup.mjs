// One-time setup for the Mint Labs human panel storage. Creates (or reuses) the Supabase project "mint-labs-panel",
// applies docs/sql/panel-v1.sql, appends SUPABASE_PANEL_URL / _ANON_KEY / _SERVICE_KEY to .env.local and writes the public
// URL + anon key into public/panel/config.js (the anon key is public by design; it only reaches the two rpc functions).
// Usage: node scripts/panel-supabase-setup.mjs [--pat-file PATH] [--org SLUG]
// The PAT is read from the memory file named below (or SUPABASE_ACCESS_TOKEN) and is never printed. Nothing is printed except refs.
import {readFileSync,appendFileSync,writeFileSync,existsSync,chmodSync} from 'node:fs';
import {randomBytes} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import path from 'node:path';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const arg=n=>{const i=process.argv.indexOf(n);return i>0?process.argv[i+1]:null;};
const patFile=arg('--pat-file')||'/Users/ryancortenbach/.claude/projects/-Users-ryancortenbach/memory/reference_supabase_cortenbach_ryan_23.md';
const pat=process.env.SUPABASE_ACCESS_TOKEN||(readFileSync(patFile,'utf8').match(/sbp_[A-Za-z0-9]+/)||[])[0];
if(!pat)throw Error('No Supabase access token found');
const api=async(method,p,body)=>{
 const res=await fetch(`https://api.supabase.com${p}`,{method,headers:{Authorization:`Bearer ${pat}`,'Content-Type':'application/json'},body:body?JSON.stringify(body):undefined});
 const text=await res.text();let json=null;try{json=JSON.parse(text);}catch{}
 if(!res.ok)throw Error(`${method} ${p} -> HTTP ${res.status}: ${(json?.message||text).slice(0,300)}`);
 return json;
};
const NAME='mint-labs-panel';
let project=(await api('GET','/v1/projects')).find(p=>p.name===NAME);
if(!project){
 const orgs=await api('GET','/v1/organizations');
 const org=arg('--org')||orgs[0]?.slug;
 const pass=randomBytes(24).toString('base64url');
 project=await api('POST','/v1/projects',{name:NAME,organization_slug:org,db_pass:pass,region:'us-east-1',plan:'free'});
 console.log('created project',project.id,project.region);
}else console.log('reusing project',project.id,project.region);
const ref=project.id;
for(let i=0;i<60;i++){
 const p=(await api('GET','/v1/projects')).find(x=>x.id===ref);
 if(p?.status==='ACTIVE_HEALTHY')break;
 if(i===59)throw Error(`project not healthy (${p?.status})`);
 await new Promise(r=>setTimeout(r,5000));
}
const sql=readFileSync(path.join(root,'docs/sql/panel-v1.sql'),'utf8');
for(let i=0;;i++){
 try{await api('POST',`/v1/projects/${ref}/database/query`,{query:sql});break;}
 catch(e){if(i>=8)throw e;await new Promise(r=>setTimeout(r,5000));}
}
console.log('schema applied');
const keys=await api('GET',`/v1/projects/${ref}/api-keys?reveal=true`);
const anon=keys.find(k=>k.name==='anon')?.api_key,service=keys.find(k=>k.name==='service_role')?.api_key;
if(!anon||!service)throw Error('API keys missing from the project');
const url=`https://${ref}.supabase.co`;
const envFile=path.join(root,'.env.local');
const cur=existsSync(envFile)?readFileSync(envFile,'utf8'):'';
const add=Object.entries({SUPABASE_PANEL_URL:url,SUPABASE_PANEL_ANON_KEY:anon,SUPABASE_PANEL_SERVICE_KEY:service}).filter(([k])=>!new RegExp(`^${k}=`,'m').test(cur));
if(add.length)appendFileSync(envFile,(cur&&!cur.endsWith('\n')?'\n':'')+add.map(([k,v])=>`${k}=${v}`).join('\n')+'\n');
chmodSync(envFile,0o600);
writeFileSync(path.join(root,'public/panel/config.js'),`// Generated by scripts/panel-supabase-setup.mjs. The anon key is public by design and can only call get_panel and submit_panel_response.\nwindow.PANEL_CONFIG=${JSON.stringify({url,anon})};\n`);
console.log('env vars added:',add.map(([k])=>k).join(', ')||'none (already present)');
console.log('project ref',ref,'region',project.region);
